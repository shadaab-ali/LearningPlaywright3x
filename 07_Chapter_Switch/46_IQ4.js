let score=85;

switch(score){
    case (score>=95): console.log("Excelent");
    break;
    
    case (score>=85): console.log("Good");
    break;
    
    case (score>=70): console.log("Distinction");
    break;

    case (score>=50): console.log("Nice");
    break;

    
    default: 
     console.log("Fail");
     break;
}